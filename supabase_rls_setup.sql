-- --------------------------------------------------------------------
-- STEP 1: CREATE OR UPDATE PROFILES TABLE
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  full_name TEXT,
  phone TEXT,
  city TEXT,
  role TEXT DEFAULT 'user', -- 'user' or 'admin'
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if they exist to avoid duplication
DROP POLICY IF EXISTS "Public profiles are viewable by everyone" ON public.profiles;
DROP POLICY IF EXISTS "Users can view all profiles" ON public.profiles;
DROP POLICY IF EXISTS "Users can insert their own profile" ON public.profiles;
DROP POLICY IF EXISTS "Users can update their own profile or admin any" ON public.profiles;
DROP POLICY IF EXISTS "Admins can delete profiles" ON public.profiles;

-- Profile Policies:
-- 1. Allow authenticated users to view all profiles (needed for feed and admin list)
CREATE POLICY "Users can view all profiles"
ON public.profiles FOR SELECT
TO authenticated
USING (true);

-- 2. Allow users to insert their own profile
CREATE POLICY "Users can insert their own profile"
ON public.profiles FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = id);

-- 3. Allow users to update their own profile, OR allow Admin to update ANY profile
CREATE POLICY "Users can update their own profile or admin any"
ON public.profiles FOR UPDATE
TO authenticated
USING (
  auth.uid() = id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
)
WITH CHECK (
  auth.uid() = id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);

-- 4. Allow Admin to delete any profile
CREATE POLICY "Admins can delete profiles"
ON public.profiles FOR DELETE
TO authenticated
USING (
  (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);


-- --------------------------------------------------------------------
-- STEP 2: AUTOMATIC TRIGGER FOR NEW USERS (SYNC AUTH.USERS -> PROFILES)
-- --------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, phone, city, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', ''),
    COALESCE(NEW.raw_user_meta_data->>'phone', ''),
    COALESCE(NEW.raw_user_meta_data->>'city', ''),
    CASE 
      WHEN NEW.email = 'pakistan.hafsa@gmail.com' THEN 'admin'
      ELSE COALESCE(NEW.raw_user_meta_data->>'role', 'user')
    END
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    full_name = CASE WHEN EXCLUDED.full_name <> '' THEN EXCLUDED.full_name ELSE public.profiles.full_name END,
    phone = CASE WHEN EXCLUDED.phone <> '' THEN EXCLUDED.phone ELSE public.profiles.phone END,
    city = CASE WHEN EXCLUDED.city <> '' THEN EXCLUDED.city ELSE public.profiles.city END,
    role = CASE 
      WHEN EXCLUDED.email = 'pakistan.hafsa@gmail.com' THEN 'admin'
      WHEN EXCLUDED.role <> '' THEN EXCLUDED.role 
      ELSE public.profiles.role 
    END,
    updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT OR UPDATE ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- --------------------------------------------------------------------
-- STEP 3: CONFIGURE "my-posts" TABLE & ROW LEVEL SECURITY (RLS)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."my-posts" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  background TEXT,
  email TEXT,
  name TEXT,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on "my-posts"
ALTER TABLE public."my-posts" ENABLE ROW LEVEL SECURITY;

-- Drop old policies to avoid conflict
DROP POLICY IF EXISTS "Allow public read access to all posts" ON public."my-posts";
DROP POLICY IF EXISTS "Allow authenticated users to create posts" ON public."my-posts";
DROP POLICY IF EXISTS "Allow users to update own posts or admin any" ON public."my-posts";
DROP POLICY IF EXISTS "Allow users to delete own posts or admin any" ON public."my-posts";

-- 1. Read Policy: Anyone (authenticated or public) can read all posts
CREATE POLICY "Allow public read access to all posts"
ON public."my-posts" FOR SELECT
USING (true);

-- 2. Insert Policy: Authenticated users can insert posts with their user_id
CREATE POLICY "Allow authenticated users to create posts"
ON public."my-posts" FOR INSERT
TO authenticated
WITH CHECK (
  auth.uid() = user_id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);

-- 3. Update Policy: Users can update their own posts; Admins can update ANY post
CREATE POLICY "Allow users to update own posts or admin any"
ON public."my-posts" FOR UPDATE
TO authenticated
USING (
  auth.uid() = user_id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
)
WITH CHECK (
  auth.uid() = user_id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);

-- 4. Delete Policy: Users can delete their own posts; Admins can delete ANY post
CREATE POLICY "Allow users to delete own posts or admin any"
ON public."my-posts" FOR DELETE
TO authenticated
USING (
  auth.uid() = user_id
  OR (auth.jwt() ->> 'email') = 'pakistan.hafsa@gmail.com'
  OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);


-- --------------------------------------------------------------------
-- STEP 4: AUTOMATICALLY ENSURE pakistan.hafsa@gmail.com IS ADMIN
-- --------------------------------------------------------------------
UPDATE public.profiles
SET role = 'admin'
WHERE email = 'pakistan.hafsa@gmail.com';

UPDATE auth.users
SET raw_user_meta_data = raw_user_meta_data || '{"role": "admin"}'::jsonb
WHERE email = 'pakistan.hafsa@gmail.com';
